"""Build the browser search index from the published HTML."""

import json
from dataclasses import dataclass, field
from html.parser import HTMLParser
from pathlib import Path
from unicodedata import normalize

ROOT = Path(__file__).resolve().parents[1]
SUBJECTS = {
    "science": "과학",
    "health": "보건",
    "social": "사회",
    "art": "미술",
    "history": "역사",
    "english": "영어",
}
TEXT_TAGS = {"h1", "h2", "h3", "p", "li", "dt", "dd", "summary", "blockquote", "figcaption"}
VOID_TAGS = {"area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "param", "source", "track", "wbr"}
SKIP_CLASSES = {"resource-list", "assessment-link", "scope-source", "back-row"}


@dataclass
class Place:
    label: str = ""
    lines: list[str] = field(default_factory=list)


@dataclass
class Element:
    tag: str
    place: str | None
    text: list[str] | None
    reads_text: bool
    is_metadata: bool
    ends_with_space: bool


class SearchReader(HTMLParser):
    def __init__(self):
        super().__init__()
        self.stack: list[Element] = []
        self.places: dict[str, Place] = {}
        self.title = ""
        self.grade = ""

    def handle_starttag(self, tag, attributes):
        attrs = dict(attributes)
        classes = set(attrs.get("class", "").split())
        parent = self.stack[-1] if self.stack else None
        place = parent.place if parent else None
        text = parent.text if parent else None
        if tag in VOID_TAGS:
            if tag == "br" and text is not None:
                text.append(" ")
            return

        place = attrs.get("data-search-section", place)
        if classes & {"lesson-section", "session"}:
            place = attrs["id"]
        if "lesson-heading" in classes:
            place = ""
        if SKIP_CLASSES & classes or attrs.get("aria-hidden") == "true" or tag in {"nav", "script"}:
            place = None
            text = None

        reads_text = place is not None and tag in TEXT_TAGS
        if reads_text:
            text = []
        metadata = "lesson-meta" in classes
        ends_with_space = tag == "span" and parent and (parent.is_metadata or parent.tag == "summary")
        self.stack.append(Element(tag, place, text, reads_text, metadata, bool(ends_with_space)))

    def handle_startendtag(self, tag, attributes):
        self.handle_starttag(tag, attributes)
        if tag not in VOID_TAGS:
            self.handle_endtag(tag)

    def handle_data(self, text):
        if self.stack and self.stack[-1].text is not None:
            self.stack[-1].text.append(text)

    def handle_endtag(self, tag):
        element = self.stack.pop()
        if element.tag != tag:
            raise ValueError(f"Expected </{element.tag}>, got </{tag}>")
        if element.ends_with_space and element.text is not None:
            element.text.append(" · " if self.stack[-1].is_metadata else " ")
        if not element.reads_text:
            return
        line = normalize("NFC", " ".join("".join(element.text).split())).removesuffix(" ·")
        if not line:
            return

        place = self.places.setdefault(element.place, Place())
        if tag == "h1":
            self.title = line
        if element.is_metadata:
            self.grade = line.split(" · ", 1)[0]
        if tag == "h2":
            place.label = line
        if tag == "summary" and element.place.startswith("session-"):
            place.label = f"{element.place.removeprefix('session-')}차시"
        if line not in place.lines:
            place.lines.append(line)


def read_page(path):
    reader = SearchReader()
    reader.feed(path.read_text(encoding="utf-8"))
    reader.close()
    if not reader.title or reader.stack:
        raise ValueError(f"Missing title or unfinished tags in {path}")

    if path.parent.name == "lessons":
        subject, number = path.stem.rsplit("-", 1)
        label = f"{SUBJECTS[subject]} {number}"
    else:
        label = "웹진 도입 기사"

    sections = []
    for anchor, place in reader.places.items():
        default_label = "표지" if anchor == "cover-title" else "수업 소개"
        lines = [label, *place.lines] if not anchor else place.lines
        sections.append({"anchor": anchor, "label": place.label or default_label, "lines": lines})
    return {
        "url": path.relative_to(ROOT).as_posix(),
        "title": reader.title,
        "label": label,
        "grade": reader.grade,
        "sections": sections,
    }


def main():
    lessons = sorted((ROOT / "lessons").glob("*.html"), key=lambda page: page.stem.rsplit("-", 1)[1])
    index = [read_page(path) for path in [*lessons, ROOT / "index.html"]]
    data = json.dumps(index, ensure_ascii=False, indent=2)
    (ROOT / "assets/search-index.js").write_text(
        "// Generated by scripts/build_search_index.py\n"
        f"const webzineSearchIndex = {data};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
